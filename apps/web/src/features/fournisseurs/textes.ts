export type CleTexte = Cle;
export const DICTIONNAIRES = { fr: FR, ar: AR, en: EN };

export function texte(lang: Lang) {
  const d: Partial<Record<Cle, string>> = lang === "en" ? EN : lang === "ar" ? AR : FR;
  return (cle: Cle, vars?: Record<string, string | number>) => {
    let s: string = d[cle] ?? FR[cle];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

const LOCALE: Record<Lang, string> = { fr: "fr-FR", ar: "ar-MA", en: "en-GB" };

/** Textes, langue et formats de la page courante. */
export function useTextes() {
  const { lang, setLang } = useLang();
  const t = texte(lang);
  const nb = (n: number | null | undefined, dec = 2) => (n == null || !Number.isFinite(n) ? "—" : new Intl.NumberFormat(LOCALE[lang], { maximumFractionDigits: dec }).format(n));
  return {
    t, lang, setLang,
    /** Libellé trilingue du référentiel. */
    l3: (l: L3 | undefined) => tr(l, lang),
    /** Contenu saisi FR / AR : langue du visiteur, sinon l'autre (avec l'attribut lang à poser). */
    bi: (fr: string | null | undefined, ar: string | null | undefined) => bilingue(fr, ar, lang),
    dh: (n: number | null | undefined, dec = 2) => (n == null || !Number.isFinite(n) ? "—" : `${nb(n, dec)} ${t("dh")}`),
    nb,
    date: (s: string | null | undefined) => (s ? new Date(s).toLocaleDateString(LOCALE[lang]) : "—"),
    /** Message lisible d'une erreur d'API (codes des Pages Functions). */
    erreur: (code: string | null) => (code ? (AR[`err_${code}` as Cle] ? t(`err_${code}` as Cle) : t("err_generique", { code })) : t("err_reseau")),
  };
}
export type Textes = ReturnType<typeof useTextes>;
