export function texte(lang: Lang) {
  const d: Partial<Record<Cle, string>> = lang === "en" ? EN : lang === "ar" ? AR : {};
  return (cle: Cle, vars?: Record<string, string | number>) => {
    let s: string = d[cle] ?? FR[cle];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}
export type T = ReturnType<typeof texte>;

const MOIS: Record<Lang, string[]> = {
  fr: ["janvier", "février", "mars", "avril", "mai", "juin", "juillet", "août", "septembre", "octobre", "novembre", "décembre"],
  en: ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"],
  ar: ["يناير", "فبراير", "مارس", "أبريل", "ماي", "يونيو", "يوليوز", "غشت", "شتنبر", "أكتوبر", "نونبر", "دجنبر"],
};
/** « octobre 2026 » depuis « 2026-10 » (ou plage « 2026-02/05 » → dernier mois). */
export function moisLisible(d: string | null, lang: Lang): string {
  if (!d) return "";
  const m = d.match(/^(\d{4})-(\d{2})(?:\/(\d{2})(?!\d))?/);
  if (!m) return d;
  const mois = Number(m[3] || m[2]);
  return `${MOIS[lang][mois - 1] || ""} ${m[1]}`.trim();
}
