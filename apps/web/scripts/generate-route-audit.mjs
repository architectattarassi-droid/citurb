/*
 * CITURBAREA — Dev Tooling — Route & CTA Audit
 * Doctrine goal: 0 page cachée / 0 page non atteignable / 0 bouton mort.
 *
 * This script scans the codebase for route usages and common dead-CTA patterns
 * and generates a TypeScript module imported by /_dev/routes.
 *
 * It runs automatically via `predev` and `prebuild`.
 */

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(process.cwd()); // apps/web
const SRC_DIR = path.join(ROOT, "src");
const OUT_FILE = path.join(SRC_DIR, "application", "routeAudit.generated.ts");

function listFiles(dir) {
  const out = [];
  const stack = [dir];
  while (stack.length) {
    const cur = stack.pop();
    const entries = fs.readdirSync(cur, { withFileTypes: true });
    for (const e of entries) {
      const p = path.join(cur, e.name);
      if (e.isDirectory()) stack.push(p);
      else out.push(p);
    }
  }
  return out;
}

const ROUTE_PATTERNS = [
  /\bto=\{?['"](\/[^'"\s}]*)['"]\}?/g,
  /\bnavigate\(\s*['"](\/[^'"\s)]*)['"]/g,
  // Template literal navigations: navigate(`/path?x=${...}`) -> capture prefix before ${ or end
  /\bnavigate\(\s*`(\/[^`$\s]*)/g,
  /\bhref=\{?['"](\/[^'"\s}]*)['"]\}?/g,
  // Template literal href: href={`/path/${id}`}
  /\bhref=\{?`(\/[^`$\s]*)/g,
  /\bwindow\.location\.(?:href|assign)\(\s*['"](\/[^'"\s)]*)['"]/g,
  /\bwindow\.location\.href\s*=\s*['"](\/[^'"\s;]*)['"]/g,
  /\bwindow\.location\.href\s*=\s*`(\/[^`$\s]*)/g,
];

const DEAD_CTA_PATTERNS = [
  { name: "href_hash", re: /\bhref=\{?['"]#['"]\}?/g },
  { name: "inline_onclick", re: /\bonclick=\{?['"]/gi },
  { name: "todo_handler", re: /TODO\s*:\s*hook|FIXME\s*:\s*hook/gi },
];

function lineOf(s, idx) {
  let line = 1;
  for (let i = 0; i < idx; i++) if (s.charCodeAt(i) === 10) line++;
  return line;
}

function normalizeRoute(r) {
  if (!r) return r;
  const q = r.indexOf("?");
  const h = r.indexOf("#");
  const cut = Math.min(q === -1 ? Infinity : q, h === -1 ? Infinity : h);
  return cut === Infinity ? r : r.slice(0, cut);
}

// Load route registry (simple parse to avoid TS runtime import)
const routeRegistryPath = path.join(SRC_DIR, "application", "routeRegistry.ts");
const routeRegistryText = fs.readFileSync(routeRegistryPath, "utf8");
const declared = new Set();
for (const m of routeRegistryText.matchAll(/\{\s*path:\s*['"]([^'"]+)['"]/g)) {
  declared.add(m[1]);
}

const files = listFiles(SRC_DIR).filter(
  f => /\.(ts|tsx)$/.test(f) && !f.endsWith("routeAudit.generated.ts")
);

const usages = [];
const deadCtas = [];

for (const f of files) {
  const rel = path.relative(ROOT, f).replace(/\\/g, "/");
  const text = fs.readFileSync(f, "utf8");

  for (const re of ROUTE_PATTERNS) {
    for (const m of text.matchAll(re)) {
      const raw = m[1];
      const route = normalizeRoute(raw);
      if (!route || !route.startsWith("/")) continue;
      if (route.startsWith("/src/") || route.startsWith("/assets/") || route.startsWith("/api")) continue;
      usages.push({ route, file: rel, line: lineOf(text, m.index ?? 0) });
    }
  }

  for (const p of DEAD_CTA_PATTERNS) {
    for (const m of text.matchAll(p.re)) {
      const ln = lineOf(text, m.index ?? 0);
      const start = Math.max(0, (m.index ?? 0) - 40);
      const end = Math.min(text.length, (m.index ?? 0) + 80);
      const snippet = text.slice(start, end).replace(/\s+/g, " ").trim();
      deadCtas.push({ kind: p.name, file: rel, line: ln, snippet });
    }
  }
}

const seenUsage = new Set();
const dedupUsages = [];
for (const u of usages) {
  const k = `${u.route}@@${u.file}@@${u.line}`;
  if (seenUsage.has(k)) continue;
  seenUsage.add(k);
  dedupUsages.push(u);
}

const unknown = dedupUsages.filter(u => !declared.has(u.route));
const unusedDeclared = [...declared].filter(
  r => !dedupUsages.some(u => u.route === r) && r !== "/_dev/routes"
);

const banner = `/**\n * AUTO-GENERATED FILE — DO NOT EDIT\n * Generated by scripts/generate-route-audit.mjs\n */\n`;

const out =
  banner +
  `export const DECLARED_ROUTES = ${JSON.stringify([...declared], null, 2)} as const;\n` +
  `export const ROUTE_USAGES = ${JSON.stringify(dedupUsages, null, 2)} as const;\n` +
  `export const UNKNOWN_ROUTE_USAGES = ${JSON.stringify(unknown, null, 2)} as const;\n` +
  `export const UNUSED_DECLARED_ROUTES = ${JSON.stringify(unusedDeclared, null, 2)} as const;\n` +
  `export const DEAD_CTA_HINTS = ${JSON.stringify(deadCtas, null, 2)} as const;\n`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, out, "utf8");

console.log(`[CIT] Route audit generated: ${path.relative(ROOT, OUT_FILE)}`);
console.log(`[CIT] Declared routes: ${declared.size}`);
console.log(`[CIT] Route usages: ${dedupUsages.length}`);
console.log(`[CIT] Unknown usages: ${unknown.length}`);
console.log(`[CIT] Unused declared: ${unusedDeclared.length}`);
console.log(`[CIT] Dead CTA hints: ${deadCtas.length}`);
